_AR_DIGITS = str.maketrans("0123456789", "٠١٢٣٤٥٦٧٨٩")


def render_statement_pdf(data: dict, lang: str) -> bytes:
    from weasyprint import HTML

    lang = lang if lang in _LABELS else "en"
    t = _LABELS[lang]
    rtl = lang == "ar"
    esc = lambda v: html.escape(str(v))  # noqa: E731

    def num(text: str) -> str:
        return text.translate(_AR_DIGITS) if rtl else text

    def money(value) -> str:
        return num(f"{value:,.2f}") + f" {t['currency']}"

    def rows(items, cells, empty_cols):
        if not items:
            return f'<tr><td colspan="{empty_cols}" class="muted">{t["none"]}</td></tr>'
        return "".join("<tr>" + "".join(f"<td>{c(i)}</td>" for c in cells) + "</tr>" for i in items)

    received_rows = rows(
        data["received"],
        [
            lambda r: num(str(r["date"])),
            lambda r: num(esc(r["unit"])) if r["kind"] == "payment" else esc(r.get("label", t["asset_sale"])),
            lambda r: t["payment"] if r["kind"] == "payment" else t["asset_sale"],
            lambda r: money(r["amount"]),
        ],
        4,
    )
    expense_rows = rows(
        data["expenses"],
        [lambda e: num(str(e["date"])), lambda e: esc(e["title"]), lambda e: esc(e["category"]), lambda e: money(e["amount"])],
        4,
    )
    unit_rows = rows(
        data["units"],
        [
            lambda u: num(esc(u["unit"])),
            lambda u: t["yes"] if u["paid_this_month"] else t["no"],
            lambda u: money(u["balance_due"]) if u["balance_due"] > 0 else "—",
        ],
        3,
    )
    align = "right" if rtl else "left"
    page = f"""<!DOCTYPE html>
<html dir="{'rtl' if rtl else 'ltr'}" lang="{lang}"><head><meta charset="utf-8"><style>
  @page {{ size: A4; margin: 14mm; }}
  body {{ font-family: "Noto Sans Arabic","Noto Sans","Segoe UI",Tahoma,Arial,sans-serif; font-size: 9.5pt; color: #161B26; }}
  .head {{ background: #254A80; color: #fff; padding: 6mm 8mm; border-radius: 3mm; }}
  .head h1 {{ margin: 0; font-size: 16pt; }} .head p {{ margin: 1mm 0 0; font-size: 9pt; opacity: .85; }}
  .sum {{ display: flex; gap: 4mm; margin: 5mm 0; }}
  .sum div {{ flex: 1; background: #EEF3FA; border-radius: 2mm; padding: 3mm 4mm; }}
  .sum small {{ color: #525B6E; display: block; }} .sum b {{ font-size: 12pt; }}
  .sum .close {{ background: #15803D; color: #fff; }} .sum .close small {{ color: #fff; opacity: .85; }}
  h2 {{ font-size: 11pt; color: #254A80; margin: 5mm 0 2mm; }}
  table {{ width: 100%; border-collapse: collapse; }}
  th {{ background: #EEF3FA; text-align: {align}; padding: 1.8mm 2.5mm; font-size: 8.5pt; }}
  td {{ padding: 1.6mm 2.5mm; border-bottom: .3mm solid #DDE1E8; text-align: {align}; unicode-bidi: plaintext; }}
  .muted {{ color: #6B7589; text-align: center; }}
  .foot {{ margin-top: 8mm; text-align: center; color: #6B7589; font-size: 8pt; }}
</style></head><body>
  <div class="head"><h1>{t['title']} — {esc(data['building'])}</h1><p>{num(data['month'])} · عِمارة.كوم | 3maracom · {t['subtitle']}</p></div>
  <div class="sum">
    <div><small>{t['opening']}</small><b>{money(data['opening_balance'])}</b></div>
    <div><small>{t['received']}</small><b>{money(data['total_received'])}</b></div>
    <div><small>{t['spent']}</small><b>{money(data['total_expenses'])}</b></div>
    <div class="close"><small>{t['closing']}</small><b>{money(data['closing_balance'])}</b></div>
  </div>
  <h2>{t['received']}</h2>
  <table><tr><th>{t['date']}</th><th>{t['unit']}</th><th>{t['details']}</th><th>{t['amount']}</th></tr>{received_rows}</table>
  <h2>{t['spent']}</h2>
  <table><tr><th>{t['date']}</th><th>{t['details']}</th><th>{t['category']}</th><th>{t['amount']}</th></tr>{expense_rows}</table>
  <h2>{t['units']} ({num(str(data['units_paid']))}/{num(str(data['units_total']))})</h2>
  <table><tr><th>{t['unit']}</th><th>{t['paid']}</th><th>{t['due']}</th></tr>{unit_rows}</table>
  <div class="foot">{t['footer']}</div>
</body></html>"""
    return HTML(string=page).write_pdf()
