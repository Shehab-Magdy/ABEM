"""Monthly statement (كشف حساب شهري): what came in, what went out, where the treasury stands."""
from __future__ import annotations

import html
from datetime import date
from decimal import Decimal

from django.db.models import Sum

ZERO = Decimal("0.00")


def parse_month(value: str | None) -> date:
    """'YYYY-MM' -> first day of that month (current month when empty). Raises ValueError."""
    if not value:
        today = date.today()
        return today.replace(day=1)
    year, month = value.split("-")
    return date(int(year), int(month), 1)


def _next_month(first: date) -> date:
    return date(first.year + (first.month == 12), first.month % 12 + 1, 1)


def build_statement(building, first_day: date) -> dict:
    """Numbers for one building and month. Opening + received - spent = closing, using the treasury rules."""
    from apps.apartments.models import Apartment
    from apps.expenses.models import Expense
    from apps.payments.models import AssetSale, Payment

    end = _next_month(first_day)  # exclusive

    def total(qs, field):
        return qs.aggregate(s=Sum(field))["s"] or ZERO

    payments = Payment.objects.filter(apartment__building=building)
    sales = AssetSale.objects.filter(asset__building=building)
    # costs only: subscriptions and late fees are charges to units, not money the building spent
    expenses = Expense.objects.filter(building=building, deleted_at__isnull=True, kind="cost")

    opening = (
        building.starting_balance
        + total(payments.filter(payment_date__lt=first_day), "amount_paid")
        + total(sales.filter(sale_date__lt=first_day), "sale_price")
        - total(expenses.filter(expense_date__lt=first_day), "amount")
    )

    month_payments = payments.filter(payment_date__gte=first_day, payment_date__lt=end).select_related("apartment")
    month_sales = sales.filter(sale_date__gte=first_day, sale_date__lt=end).select_related("asset")
    month_expenses = expenses.filter(expense_date__gte=first_day, expense_date__lt=end).select_related("category")

    received = [
        {"date": p.payment_date, "unit": p.apartment.unit_number, "kind": "payment", "amount": p.amount_paid}
        for p in month_payments.order_by("payment_date", "created_at")
    ] + [
        {"date": s.sale_date, "unit": "", "kind": "asset_sale", "label": s.asset.name, "amount": s.sale_price}
        for s in month_sales.order_by("sale_date")
    ]
    spent = [
        {"date": e.expense_date, "title": e.title, "category": e.category.name, "amount": e.amount}
        for e in month_expenses.order_by("expense_date", "created_at")
    ]
    total_received = sum((r["amount"] for r in received), ZERO)
    total_spent = sum((e["amount"] for e in spent), ZERO)

    # Units: unit numbers only (no names), so the statement is safe to share with the building
    paid_units = {p.apartment_id for p in month_payments}
    units = [
        {"unit": a.unit_number, "paid_this_month": a.pk in paid_units, "balance_due": max(a.balance, ZERO)}
        for a in Apartment.objects.filter(building=building).order_by("floor", "unit_number")
    ]

    return {
        "building": building.name,
        "month": first_day.strftime("%Y-%m"),
        "opening_balance": opening,
        "received": received,
        "total_received": total_received,
        "expenses": spent,
        "total_expenses": total_spent,
        "closing_balance": opening + total_received - total_spent,
        "units": units,
        "units_paid": sum(1 for u in units if u["paid_this_month"]),
        "units_total": len(units),
    }


