"""Annual report (التقرير السنوي) for the general assembly: the year's collections, spending and dues."""
from __future__ import annotations

import html
from datetime import date
from decimal import Decimal

from django.db.models import Count, Sum
from django.db.models.functions import TruncMonth

ZERO = Decimal("0.00")


def build_annual_report(building, year: int) -> dict:
    """Numbers for one building and calendar year, using the treasury rules (costs only, approved only)."""
    from apps.apartments.models import Apartment
    from apps.expenses.models import Expense
    from apps.payments.models import AssetSale, Payment

    start, end = date(year, 1, 1), date(year + 1, 1, 1)  # end is exclusive

    def total(qs, field):
        return qs.aggregate(s=Sum(field))["s"] or ZERO

    payments = Payment.objects.filter(apartment__building=building)
    sales = AssetSale.objects.filter(asset__building=building)
    costs = Expense.objects.filter(building=building, deleted_at__isnull=True, kind="cost", approval_status="approved")

    opening = (
        building.starting_balance
        + total(payments.filter(payment_date__lt=start), "amount_paid")
        + total(sales.filter(sale_date__lt=start), "sale_price")
        - total(costs.filter(expense_date__lt=start), "amount")
    )

    year_payments = payments.filter(payment_date__gte=start, payment_date__lt=end)
    year_sales = sales.filter(sale_date__gte=start, sale_date__lt=end)
    year_costs = costs.filter(expense_date__gte=start, expense_date__lt=end)

    collected = {m: ZERO for m in range(1, 13)}
    spent = {m: ZERO for m in range(1, 13)}
    for row in year_payments.annotate(m=TruncMonth("payment_date")).values("m").annotate(s=Sum("amount_paid")):
        collected[row["m"].month] += row["s"]
    for row in year_sales.annotate(m=TruncMonth("sale_date")).values("m").annotate(s=Sum("sale_price")):
        collected[row["m"].month] += row["s"]
    for row in year_costs.annotate(m=TruncMonth("expense_date")).values("m").annotate(s=Sum("amount")):
        spent[row["m"].month] += row["s"]

    by_category = [
        {"category": r["category__name"], "count": r["n"], "amount": r["s"]}
        for r in year_costs.values("category__name").annotate(s=Sum("amount"), n=Count("id")).order_by("-s")
    ]
    total_collected = sum(collected.values(), ZERO)
    total_spent = sum(spent.values(), ZERO)

    # Dues as of today (what the assembly still has to chase); unit numbers only, no names
    owing = [
        {"unit": a.unit_number, "balance_due": a.balance}
        for a in Apartment.objects.filter(building=building).order_by("floor", "unit_number")
        if a.balance > 0
    ]
    return {
        "building": building.name,
        "year": year,
        "opening_balance": opening,
        "total_collected": total_collected,
        "total_expenses": total_spent,
        "closing_balance": opening + total_collected - total_spent,
        "months": [{"month": m, "collected": collected[m], "expenses": spent[m]} for m in range(1, 13)],
        "expenses_by_category": by_category,
        "unpaid_units": owing,
        "total_unpaid": sum((u["balance_due"] for u in owing), ZERO),
    }


